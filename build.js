#!/usr/bin/env node
// Markdown -> HTML build pipeline for isaacmp.xyz.
//
// Reads articles-md/*.md and posts-md/*.md, renders each to HTML wrapped in
// the site's existing article/post template (matching articles/template.html
// and posts/template.html), and regenerates articles-data.js / posts-data.js
// (the registries that drive the homepage lists, search, and /tags.html)
// from the same front matter.
//
// Run manually with `node build.js`, or wire up hooks/post-receive so it
// runs automatically on push to the bare repo on the NAS.
//
// Safety:
//   - Every output file is written to a .tmp path first, then renamed into
//     place — a failed/interrupted build never leaves a half-written page.
//   - A file that fails to parse/convert is skipped (previous HTML left
//     untouched); the rest of the build continues.
//   - Only HTML files this script itself generated (marked with the
//     "AUTO-GENERATED by build.js" comment) are ever deleted or overwritten
//     during cleanup — hand-written pages like articles/poorcharlie.html are
//     never touched, even if their slug isn't in articles-md/.
//   - Registry files (articles-data.js / posts-data.js) are rebuilt from
//     front matter, but any existing entry whose HTML file still exists
//     (hand-written pages, or a page that errored *this* run but built
//     fine before) is carried over unchanged rather than dropped.

'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const matter = require('gray-matter');
const { marked } = require('marked');

const ROOT = __dirname;
const SITE_URL = 'https://isaacmp.xyz';
const MARKER = 'AUTO-GENERATED by build.js';

marked.setOptions({ gfm: true, breaks: false });

// Articles now publish straight to the repo root (isaacmp.xyz/slug, Sivers-
// style short links) instead of /articles/slug.html, so their output shares
// a directory with index.html, tags.html, and the other top-level files. A
// slug matching one of these would silently overwrite that file on build.
const RESERVED_ROOT_SLUGS = new Set([
  'index', 'tags', 'bookmarks', 'search', 'style', 'theme', 'build',
  'sitemap', 'robots', 'cname', 'favicon',
  'articles-data', 'posts-data', 'now-data', 'bookmarks-data'
]);

// "Now" entries are simpler than articles/posts: one entry per date, no
// separate HTML page, just a {date, html} object appended to now-data.js.
// So they get their own small build function below instead of living in
// the TYPES/buildType() machinery, which assumes a rendered page per file.
const NOW_SRC_DIR = path.join(ROOT, 'now-md');
const NOW_REGISTRY_FILE = path.join(ROOT, 'now-data.js');
const NOW_REGISTRY_VAR = 'NOW_ENTRIES';
const NOW_DATE_RE = /^\d{4}-\d{2}(-\d{2})?$/;

const TYPES = [
  {
    name: 'article',
    label: 'Articles',
    srcDir: path.join(ROOT, 'articles-md'),
    outDir: ROOT,
    registryFile: path.join(ROOT, 'articles-data.js'),
    registryVar: 'ARTICLES',
    urlDir: '',
    assetPrefix: '',
    backLink: 'site.html#articles',
    articleIdAttr: '',
    defaultRobots: 'index, follow',
    reservedSlugs: RESERVED_ROOT_SLUGS
  },
  {
    name: 'post',
    label: 'Posts',
    srcDir: path.join(ROOT, 'posts-md'),
    outDir: path.join(ROOT, 'posts'),
    registryFile: path.join(ROOT, 'posts-data.js'),
    registryVar: 'POSTS',
    urlDir: 'posts',
    assetPrefix: '../',
    backLink: '../site.html#posts',
    articleIdAttr: ' id="post-body"',
    defaultRobots: 'index, follow'
  },
  {
    // Project "wiki" pages: projects-md/<slug>.md -> projects/<slug>.html.
    // Same markdown pipeline, but the header shows a tagline, a visit link
    // and screenshots instead of a date, and a contents list is generated
    // from the ## headings.
    name: 'project',
    label: 'Projects',
    srcDir: path.join(ROOT, 'projects-md'),
    outDir: path.join(ROOT, 'projects'),
    registryFile: path.join(ROOT, 'projects-data.js'),
    registryVar: 'PROJECTS',
    urlDir: 'projects',
    assetPrefix: '../',
    backLink: '../site.html#projects',
    articleIdAttr: '',
    defaultRobots: 'index, follow'
  }
];

// ---------- small helpers ----------

function escapeHtml(str) {
  return String(str == null ? '' : str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function jsStringEscape(str) {
  return String(str == null ? '' : str).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

// gray-matter/js-yaml auto-casts unquoted YAML dates (date: 2026-08-06) into
// JS Date objects — normalize either that or a plain string back to
// 'YYYY-MM-DD' (or pass a partial 'YYYY-MM' straight through).
function normalizeDate(value) {
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value == null ? '' : value).trim();
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

// '2026-08-06' -> 'Aug 6, 2026' ; '2026-08' -> 'Aug, 2026'
function formatDatetimeLabel(iso) {
  const parts = iso.split('-');
  const mi = parts.length >= 2 ? parseInt(parts[1], 10) - 1 : NaN;
  if (Number.isNaN(mi) || mi < 0 || mi > 11) return iso;
  if (parts.length >= 3) return `${MONTHS[mi]} ${parseInt(parts[2], 10)}, ${parts[0]}`;
  return `${MONTHS[mi]}, ${parts[0]}`;
}

// '2026-08-06' or '2026-08' -> 'Aug, 2026' (used for the homepage list's
// dateLabel, unless the front matter provides an explicit override)
function formatDateLabel(iso) {
  const parts = iso.split('-');
  const mi = parts.length >= 2 ? parseInt(parts[1], 10) - 1 : NaN;
  if (Number.isNaN(mi) || mi < 0 || mi > 11) return iso;
  return `${MONTHS[mi]}, ${parts[0]}`;
}

function tagChips(tags) {
  if (!tags || !tags.length) return '';
  const chips = tags
    .map(t => `<a class="tag" href="/tags.html?t=${encodeURIComponent(t)}">${escapeHtml(t)}</a>`)
    .join('');
  return `<span class="tags">${chips}</span>`;
}

function listMarkdownFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter(f => f.endsWith('.md') && !f.startsWith('_'))
    .sort();
}

// Atomic write: build to <path>.tmp, then rename over the real path. A
// crash or thrown error between these two lines leaves the live file
// exactly as it was; the rename itself is atomic on the same filesystem.
function writeFileAtomic(destPath, content) {
  fs.mkdirSync(path.dirname(destPath), { recursive: true });
  const tmpPath = destPath + '.tmp';
  fs.writeFileSync(tmpPath, content, 'utf8');
  fs.renameSync(tmpPath, destPath);
}

// ---------- page template (mirrors articles/template.html & posts/template.html) ----------

function renderPage(type, meta, bodyHtml, srcRelPath) {
  const urlPath = type.urlDir ? `${type.urlDir}/${meta.slug}.html` : `${meta.slug}.html`;
  const url = `${SITE_URL}/${urlPath}`;
  const titleEsc = escapeHtml(meta.title);
  const descEsc = escapeHtml(meta.description);
  const robots = meta.robots || type.defaultRobots;
  const timeDisplay = formatDatetimeLabel(meta.date);
  const isProject = type.name === 'project';
  const footer = type.name === 'post' ? '\n\n  <p><a href="index.html">&larr; all posts</a></p>' : '';
  let wikiBody = bodyHtml;
  let toc = '';
  if (isProject) {
    // give each ## heading an id and build a contents list from them
    const heads = [];
    wikiBody = bodyHtml.replace(/<h2>([\s\S]*?)<\/h2>/g, (m, inner) => {
      const id = inner.replace(/<[^>]+>/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      heads.push({ id, text: inner.replace(/<[^>]+>/g, '') });
      return `<h2 id="${id}">${inner}</h2>`;
    });
    if (heads.length >= 3) {
      toc = `<nav class="wiki-toc" aria-label="Contents"><span class="wiki-toc-label">Contents</span>${heads.map(h => `<a href="#${h.id}">${escapeHtml(h.text)}</a>`).join('')}</nav>`;
    }
  }
  const headerHtml = isProject
    ? `<header class="article-header wiki-header">
      <h3>${titleEsc}</h3>
      <p class="article-meta">${meta.url ? `<a class="wiki-visit" href="${escapeHtml(meta.url)}">Visit ${escapeHtml(meta.url.replace(/^https?:\/\//, '').replace(/\/$/, ''))} ↗</a>` : ''} ${tagChips(meta.tags)}</p>
      ${meta.description ? `<p class="wiki-tagline">${descEsc}</p>` : ''}
    </header>
${meta.images.length ? `    <div class="wiki-images">${meta.images.map(src => `<a href="${escapeHtml(src.startsWith('/') ? src : '../' + src)}"><img src="${escapeHtml(src.startsWith('/') ? src : '../' + src)}" alt="" loading="lazy"></a>`).join('')}</div>\n` : ''}${toc ? `    ${toc}\n` : ''}`
    : `<header class="article-header">
      <h3>${titleEsc}</h3>
      <p class="article-meta"><time datetime="${meta.date}">${timeDisplay}</time> ${tagChips(meta.tags)}</p>
    </header>`;
  // match the 4-space indent the rest of the site's hand-written .article-content bodies use
  const indentedBody = wikiBody
    .replace(/\n$/, '')
    .split('\n')
    .map(line => (line ? `    ${line}` : line))
    .join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<!-- ${MARKER} from ${srcRelPath} — do not edit this file directly, edit the source .md instead -->
<meta name="viewport" content="width=device-width, initial-scale=1.0">

<title>${titleEsc} — Isaac</title>
<meta name="description" content="${descEsc}">
<link rel="canonical" href="${url}">
<meta name="robots" content="${robots}">

<meta property="og:type" content="article">
<meta property="og:title" content="${titleEsc}">
<meta property="og:description" content="${descEsc}">
<meta property="og:url" content="${url}">
<meta name="twitter:card" content="summary">
<meta name="twitter:title" content="${titleEsc}">
<meta name="twitter:description" content="${descEsc}">

<meta name="theme-color" content="#F7F7F5">
<meta name="theme-color" content="#17171A" media="(prefers-color-scheme: dark)">

<link rel="icon" href="${type.assetPrefix}favicon.svg" type="image/svg+xml">

<link rel="preload" href="/fonts/charter-regular.woff2" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="/fonts/win95fa-latin-400-normal.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="${type.assetPrefix}style.css">

<script type="application/ld+json">
{
  "@context": "https://schema.org",
  "@type": "BlogPosting",
  "headline": "${titleEsc}",
  "datePublished": "${meta.date}",
  "author": { "@type": "Person", "name": "Isaac Morris-Perrott", "url": "${SITE_URL}/" }
}
</script>
</head>
<body>

<main>
  <a href="${type.backLink}" class="back">&larr; isaacmp.xyz</a>

  <article class="article-content"${type.articleIdAttr}>
    ${headerHtml}

${indentedBody}
  </article>${footer}
</main>

<script src="/back.js"></script>
<script src="/search.js" defer></script>
<script src="/prefetch.js" defer></script>
<script src="/dock.js" defer></script>
</body>
</html>
`;
}

// ---------- registry (articles-data.js / posts-data.js) ----------

function loadExistingRegistry(type) {
  if (!fs.existsSync(type.registryFile)) return [];
  const src = fs.readFileSync(type.registryFile, 'utf8');
  try {
    // Top-level `const`/`let` don't become properties of the vm context
    // object (same reason `window.FOO` doesn't work for a top-level `const
    // FOO` in a browser <script> — see search.js) — appending the variable
    // name as a trailing expression and reading the script's completion
    // value sidesteps that instead of relying on the sandbox object.
    const wrapped = `${src}\n${type.registryVar};`;
    const result = vm.runInNewContext(wrapped, {}, { timeout: 1000, filename: type.registryFile });
    return Array.isArray(result) ? result : [];
  } catch (err) {
    console.error(`  ! could not parse existing ${path.basename(type.registryFile)} (${err.message}) — treating as empty`);
    return [];
  }
}

function toRegistryEntry(type, meta) {
  if (type.name === 'article') {
    return {
      slug: meta.slug,
      title: meta.title,
      file: `${meta.slug}.html`,
      date: meta.date,
      dateLabel: meta.dateLabel,
      tags: meta.tags,
      description: meta.description
    };
  }
  if (type.name === 'project') {
    return {
      slug: meta.slug,
      title: meta.title,
      date: meta.date,
      tags: meta.tags,
      description: meta.description,
      url: meta.url,
      images: meta.images
    };
  }
  return {
    slug: meta.slug,
    title: meta.title,
    date: meta.date,
    tags: meta.tags,
    description: meta.description
  };
}

function serializeTags(tags) {
  if (!tags || !tags.length) return '[]';
  return `[${tags.map(t => `'${jsStringEscape(t)}'`).join(', ')}]`;
}

function serializeRegistry(type, entries) {
  const sorted = [...entries].sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

  const lines = sorted.map(e => {
    if (type.name === 'project') {
      return `  { slug: '${jsStringEscape(e.slug)}', title: '${jsStringEscape(e.title)}', date: '${jsStringEscape(e.date)}', tags: ${serializeTags(e.tags)}, description: '${jsStringEscape(e.description || '')}', url: '${jsStringEscape(e.url || '')}', images: ${serializeTags(e.images)} },`;
    }
    if (type.name === 'article') {
      return `  { slug: '${jsStringEscape(e.slug)}', title: '${jsStringEscape(e.title)}', file: '${jsStringEscape(e.file)}', date: '${jsStringEscape(e.date)}', dateLabel: '${jsStringEscape(e.dateLabel)}', tags: ${serializeTags(e.tags)}, description: '${jsStringEscape(e.description || '')}' },`;
    }
    return `  { slug: '${jsStringEscape(e.slug)}', title: '${jsStringEscape(e.title)}', date: '${jsStringEscape(e.date)}', tags: ${serializeTags(e.tags)}, description: '${jsStringEscape(e.description || '')}' },`;
  });

  const srcGlob = `${path.basename(type.srcDir)}/*.md`;
  return (
    `// AUTO-GENERATED by build.js from ${srcGlob} front matter.\n` +
    `// Do not edit this file by hand for those entries — edit the .md source's\n` +
    `// front matter instead and re-run \`node build.js\` (or push, if the\n` +
    `// post-receive hook is set up). Entries with no matching .md source (or\n` +
    `// whose page errored on the last build) are carried over unchanged, as\n` +
    `// long as their HTML file still exists.\n` +
    `const ${type.registryVar} = [\n${lines.join('\n')}\n];\n`
  );
}

// ---------- build one content type ----------

function buildType(type) {
  const files = listMarkdownFiles(type.srcDir);
  const built = [];
  const errors = [];
  const knownSlugs = new Set();

  for (const file of files) {
    const slug = file.replace(/\.md$/, '');
    knownSlugs.add(slug);
    const srcPath = path.join(type.srcDir, file);
    const srcRelPath = path.relative(ROOT, srcPath);
    const outPath = path.join(type.outDir, `${slug}.html`);

    try {
      const raw = fs.readFileSync(srcPath, 'utf8');
      const parsed = matter(raw);
      const fm = parsed.data || {};

      if (!fm.title || !String(fm.title).trim()) throw new Error('missing required "title" in front matter');
      if (!fm.date) throw new Error('missing required "date" in front matter');
      if (type.reservedSlugs && type.reservedSlugs.has(slug)) {
        throw new Error(`slug "${slug}" collides with a reserved top-level file — rename ${file}`);
      }

      const date = normalizeDate(fm.date);
      const meta = {
        slug,
        title: String(fm.title).trim(),
        date,
        dateLabel: fm.dateLabel ? String(fm.dateLabel) : formatDateLabel(date),
        tags: Array.isArray(fm.tags) ? fm.tags.map(String) : [],
        description: fm.description ? String(fm.description) : '',
        robots: fm.robots ? String(fm.robots) : null,
        url: fm.url ? String(fm.url) : '',
        images: Array.isArray(fm.images) ? fm.images.map(String) : []
      };

      const bodyHtml = marked.parse(parsed.content || '');
      const html = renderPage(type, meta, bodyHtml, srcRelPath);

      writeFileAtomic(outPath, html);
      built.push(meta);
      console.log(`  ✓ ${slug}`);
    } catch (err) {
      errors.push({ file: srcRelPath, message: err.message });
      console.error(`  ✗ ${srcRelPath}: ${err.message}`);
    }
  }

  const removed = reconcileOutputDir(type, knownSlugs);

  // Registry: fresh entries from this run's successful builds, plus any
  // existing entry whose slug wasn't freshly rebuilt this run but whose
  // HTML file still exists on disk. That covers two cases identically:
  //   - genuinely hand-written pages (no .md source at all), and
  //   - a page that built fine on some earlier run but errored *this* run
  //     (its HTML is deliberately left untouched, so its listing should be
  //     too — otherwise it'd still be a live page that's vanished from the
  //     homepage/search/tags, which is worse than just leaving it alone).
  // Reconciliation above already deleted anything that's genuinely gone, so
  // "HTML still exists" is exactly the right test here.
  const existing = loadExistingRegistry(type);
  const builtSlugs = new Set(built.map(m => m.slug));
  const carriedOver = existing.filter(
    e => e && e.slug && !builtSlugs.has(e.slug) && fs.existsSync(path.join(type.outDir, `${e.slug}.html`))
  );
  const finalEntries = [...built.map(m => toRegistryEntry(type, m)), ...carriedOver];
  writeFileAtomic(type.registryFile, serializeRegistry(type, finalEntries));

  return { built, errors, removed, carriedOver: carriedOver.length };
}

// Deletes only HTML files this script previously generated (carries the
// AUTO-GENERATED marker) whose .md source no longer exists — so a renamed
// or deleted .md file doesn't leave an orphaned page live, while
// hand-written pages are never touched regardless of their slug.
function reconcileOutputDir(type, knownSlugs) {
  if (!fs.existsSync(type.outDir)) return [];
  const removed = [];
  for (const entry of fs.readdirSync(type.outDir)) {
    if (!entry.endsWith('.html')) continue;
    const slug = entry.replace(/\.html$/, '');
    if (knownSlugs.has(slug)) continue;
    const fullPath = path.join(type.outDir, entry);
    let content;
    try {
      content = fs.readFileSync(fullPath, 'utf8');
    } catch (err) {
      continue;
    }
    if (content.includes(MARKER)) {
      fs.unlinkSync(fullPath);
      removed.push(entry);
      console.log(`  − removed orphaned ${path.join(type.urlDir, entry)} (no matching .md source)`);
    }
  }
  return removed;
}

// ---------- "now" entries (now-md/*.md -> now-data.js) ----------
//
// Each file is one entry: filename is the date (e.g. now-md/2026-09-17.md,
// or now-md/2026-09.md for a monthly-only entry), body is plain markdown,
// no front matter required. An explicit `date:` in front matter overrides
// the filename if present.

function serializeNowRegistry(entries) {
  const lines = entries.map(
    e => `  { date: ${JSON.stringify(e.date)}, html: ${JSON.stringify(e.html)} },`
  );
  return (
    `// AUTO-GENERATED by build.js from now-md/*.md (one file per entry, e.g.\n` +
    `// now-md/2026-09-17.md). Do not hand-edit this file — add or edit a .md\n` +
    `// file in now-md/ and re-run \`node build.js\` (or push, if the\n` +
    `// post-receive hook is set up). Entries with no matching .md source are\n` +
    `// carried over unchanged, so anything written before this pipeline\n` +
    `// existed keeps working untouched.\n` +
    `//\n` +
    `// Single source of truth for the "Now" widget on the homepage and its\n` +
    `// history at /now/. Sorted newest first: the homepage always shows\n` +
    `// entries[0], and /now lists all of them.\n` +
    `const ${NOW_REGISTRY_VAR} = [\n${lines.join('\n')}\n];\n`
  );
}

function buildNow() {
  const files = listMarkdownFiles(NOW_SRC_DIR);
  const built = [];
  const errors = [];

  for (const file of files) {
    const slug = file.replace(/\.md$/, '');
    const srcPath = path.join(NOW_SRC_DIR, file);
    const srcRelPath = path.relative(ROOT, srcPath);

    try {
      const raw = fs.readFileSync(srcPath, 'utf8');
      const parsed = matter(raw);
      const fm = parsed.data || {};
      const date = normalizeDate(fm.date || slug);

      if (!NOW_DATE_RE.test(date)) {
        throw new Error(
          `date "${date}" is not YYYY-MM-DD (or YYYY-MM) — name the file e.g. 2026-09-17.md, or add a "date:" front matter override`
        );
      }

      const html = marked.parse(parsed.content || '').trim();
      if (!html) throw new Error('empty body');

      built.push({ date, html });
      console.log(`  ✓ ${slug}`);
    } catch (err) {
      errors.push({ file: srcRelPath, message: err.message });
      console.error(`  ✗ ${srcRelPath}: ${err.message}`);
    }
  }

  // Same carry-over principle as buildType(): any existing entry whose date
  // wasn't freshly (re)built this run is kept as-is, so hand-written legacy
  // entries (or a file that errored this run) never silently disappear.
  const existing = loadExistingRegistry({ registryFile: NOW_REGISTRY_FILE, registryVar: NOW_REGISTRY_VAR });
  const builtDates = new Set(built.map(e => e.date));
  const carriedOver = existing.filter(e => e && e.date && typeof e.html === 'string' && !builtDates.has(e.date));

  const finalEntries = [...built, ...carriedOver].sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
  writeFileAtomic(NOW_REGISTRY_FILE, serializeNowRegistry(finalEntries));

  return { built, errors, carriedOver: carriedOver.length, entries: finalEntries };
}

// ---------- cache-busting ----------
//
// GitHub Pages lets browsers cache files for 10 minutes, so right after a
// deploy a phone can hold the NEW html with the OLD style.css (or the other
// way round) and render a broken page. Every local css/js reference is given
// a ?v=<hash of that file's contents>, so a page can only ever pair with the
// exact asset version it was built against.

const ASSETS = ['style.css', 'dock.js', 'search.js', 'prefetch.js', 'back.js', 'now-data.js', 'posts-data.js', 'articles-data.js', 'bookmarks-data.js', 'uses-data.js', 'projects-data.js'];

function versionAssets() {
  const crypto = require('crypto');
  const hashes = {};
  for (const a of ASSETS) {
    const f = path.join(ROOT, a);
    if (fs.existsSync(f)) hashes[a] = crypto.createHash('md5').update(fs.readFileSync(f)).digest('hex').slice(0, 8);
  }
  const pages = [];
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.name === 'node_modules' || e.name.startsWith('.') || e.name === 'layout-shots') continue;
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name.endsWith('.html')) pages.push(full);
    }
  })(ROOT);
  const re = new RegExp('((?:href|src)="(?:/|\\.\\./|\\./)?)(' + ASSETS.map(a => a.replace('.', '\\.')).join('|') + ')(?:\\?v=[0-9a-f]+)?"', 'g');
  let touched = 0;
  for (const p of pages) {
    const html = fs.readFileSync(p, 'utf8');
    const next = html.replace(re, (m, pre, name) => hashes[name] ? `${pre}${name}?v=${hashes[name]}"` : m);
    if (next !== html) { fs.writeFileSync(p, next, 'utf8'); touched++; }
  }
  console.log(`\nVersioned asset links in ${touched} page(s).`);
}

// ---------- main ----------

// Stamps today's date into the homepage's "Last Updated" field, so the page
// needs no runtime API call to show it.
// The Now card on the home page is written into site.html at build time
// (between the <!--now-start--> / <!--now-end--> markers), so it is in the
// page from the first byte: no script, no flash, nothing that can shift.
// The entry's paragraphs run together as one block; CSS clamps it to a fixed
// number of lines, so a long entry never takes more room.
function stampNow(entries) {
  const file = path.join(ROOT, 'site.html');
  if (!fs.existsSync(file) || !entries || !entries.length) return;
  const e = entries[0];
  const text = [...e.html.matchAll(/<p>([\s\S]*?)<\/p>/g)].map(m => m[1].trim()).join(' ');
  const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const [y, m, d] = e.date.split('-');
  const label = `${d ? String(Number(d)) + ' ' : ''}${MONTHS[Number(m) - 1]} ${y}`;
  const dateTag = `<time datetime="${escapeHtml(e.date)}">${label}</time>`;
  // "Full entry" opens the whole entry in a native popover (no JS: the
  // browser handles open, Esc and click-outside). Browsers without the
  // popover API keep a plain link to /now/ instead.
  const block = `<!--now-start-->
      <div class="now-label">Now · ${dateTag}</div>
      <p class="now-text">${text}</p>
      <button type="button" class="now-more" popovertarget="now-full">Full entry →</button>
      <a class="now-more now-more--link" href="/now/">Full entry →</a>
      <div id="now-full" class="now-pop" popover aria-label="Now">
        <div class="now-pop-head">
          <span class="now-label">Now · ${dateTag}</span>
          <span class="now-pop-actions">
            <a class="now-pop-all" href="/now/"><span class="trim">All entries</span><svg class="ico" viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M5 12h14M13 6l6 6-6 6"/></svg></a>
            <button type="button" class="now-pop-close" popovertarget="now-full" popovertargetaction="hide" aria-label="Close"><svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><path d="M6 6l12 12M18 6L6 18"/></svg></button>
          </span>
        </div>
        <div class="now-pop-body">${e.html}</div>
      </div>
    <!--now-end-->`;
  const html = fs.readFileSync(file, 'utf8');
  const next = html.replace(/<!--now-start-->[\s\S]*?<!--now-end-->/, () => block);
  if (next !== html) writeFileAtomic(file, next);
}

function stampLastUpdated() {
  const file = path.join(ROOT, 'site.html');
  if (!fs.existsSync(file)) return;
  const d = new Date();
  const pad = n => String(n).padStart(2, '0');
  const today = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  const html = fs.readFileSync(file, 'utf8');
  const next = html.replace(/(<span id="last-updated">)[^<]*(<\/span>)/, `$1${today}$2`);
  if (next !== html) writeFileAtomic(file, next);
}

function main() {
  const results = [];
  for (const type of TYPES) {
    const outLabel = type.outDir === ROOT ? './' : `${path.basename(type.outDir)}/`;
    console.log(`\nBuilding ${type.label.toLowerCase()} (${path.basename(type.srcDir)}/ -> ${outLabel})...`);
    const files = listMarkdownFiles(type.srcDir);
    if (!files.length) {
      console.log(`  (no .md files found in ${path.basename(type.srcDir)}/)`);
    }
    results.push({ type, result: buildType(type) });
  }

  console.log(`\nBuilding now entries (now-md/ -> now-data.js)...`);
  if (!listMarkdownFiles(NOW_SRC_DIR).length) {
    console.log(`  (no .md files found in now-md/)`);
  }
  const nowResult = buildNow();
  stampNow(nowResult.entries);
  stampLastUpdated();
  versionAssets();

  let totalBuilt = 0, totalErrors = 0, totalRemoved = 0;
  console.log('\nSummary');
  for (const { type, result } of results) {
    totalBuilt += result.built.length;
    totalErrors += result.errors.length;
    totalRemoved += result.removed.length;
    console.log(
      `  ${type.label}: ${result.built.length} built, ${result.errors.length} error(s), ` +
      `${result.removed.length} removed, ${result.carriedOver} entr${result.carriedOver === 1 ? 'y' : 'ies'} carried over unchanged`
    );
  }
  totalBuilt += nowResult.built.length;
  totalErrors += nowResult.errors.length;
  console.log(
    `  Now: ${nowResult.built.length} built, ${nowResult.errors.length} error(s), ` +
    `${nowResult.carriedOver} entr${nowResult.carriedOver === 1 ? 'y' : 'ies'} carried over unchanged`
  );
  console.log(`  Total: ${totalBuilt} built, ${totalErrors} error(s), ${totalRemoved} removed\n`);

  if (totalErrors > 0) process.exitCode = 1;
}

main();
